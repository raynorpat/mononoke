/// Builder to generate a bundle2.
pub struct Bundle2EncodeBuilder<W> {
    writer: W,
    header: StreamHeader,
    compressor_type: CompressorType,
    parts: Vec<PartEncode>,
}

impl<W> Bundle2EncodeBuilder<W>
where
    W: AsyncWrite + Unpin + Send,
{
    pub fn new(writer: W) -> Self {
        Bundle2EncodeBuilder {
            writer,
            header: StreamHeader {
                m_stream_params: HashMap::new(),
                a_stream_params: HashMap::new(),
            },
            compressor_type: CompressorType::Uncompressed,
            parts: Vec::new(),
        }
    }

    pub fn add_stream_param(&mut self, key: String, val: String) -> Result<&mut Self> {
        if key.to_lowercase() == "compression" {
            let msg = "stream compression should be set through set_compressor_type";
            bail!(ErrorKind::Bundle2Encode(msg.into()));
        }
        if is_mandatory_param(&key)
            .chain_err(|| ErrorKind::Bundle2Encode("stream key is invalid".into()))?
        {
            self.header.m_stream_params.insert(key.to_lowercase(), val);
        } else {
            self.header.a_stream_params.insert(key.to_lowercase(), val);
        }
        Ok(self)
    }

    pub fn add_part(&mut self, part: PartEncodeBuilder) -> &mut Self {
        let part_id = self.parts.len() as u32;
        self.parts.push(part.build(part_id));
        self
    }

    pub fn set_compressor_type(&mut self, ct: CompressorType) -> &mut Self {
        self.compressor_type = ct;
        self
    }

    pub fn build(self) -> Bundle2Encode<W> {
        let mut mparams = self.header.m_stream_params;

        // The compression type becomes a mandatory param.
        mparams.insert(
            "compression".into(),
            get_compression_param(&self.compressor_type).into(),
        );

        // Build the buffer required for the stream header.
        let mut header_buf: Vec<u8> = Vec::new();

        header_buf.put_slice(b"HG20");
        // Reserve 4 bytes for the length.
        header_buf.put_u32(0);
        // Now write out the stream header.

        let params = mparams
            .into_iter()
            .map(|x| (capitalize_first(x.0), x.1))
            .chain(self.header.a_stream_params);
        Self::build_stream_params(params, &mut header_buf);

        let header_len = (header_buf.len() - 8) as u32;
        BigEndian::write_u32(&mut header_buf[4..], header_len);

        let task_waker = Arc::new(Mutex::new(futures::task::noop_waker()));
        Bundle2Encode {
            task_waker: Arc::clone(&task_waker),
            state: EncodeState::Start(StartState {
                writer: self.writer,
                compressor_type: self.compressor_type,
                header_buf: Cursor::new(Bytes::from(header_buf)),
                parts: self.parts,
                task_waker,
            }),
        }
    }

    fn build_stream_params<I>(params: I, header_buf: &mut Vec<u8>)
    where
        I: Iterator<Item = (String, String)>,
    {
        let mut first = true;
        for (key, val) in params {
            if !first {
                header_buf.push(b' ');
            }
            first = false;
            header_buf.extend_from_slice(percent_encode(&key).as_bytes());
            header_buf.push(b'=');
            header_buf.extend_from_slice(percent_encode(&val).as_bytes());
        }
    }
}

/// A sink that chunks generated by PartEncodes goes into.
type PartSink<W> = FramedWrite<Compressor<WakeWriter<W>>, ChunkEncoder>;

enum EncodeState<W> {
    Start(StartState<W>),
    Parts(PartsState<W>),
    Finish(Compressor<WakeWriter<W>>),
    Done,
    Invalid,
}

impl<W> EncodeState<W> {
    fn take(&mut self) -> Self {
        mem::replace(self, EncodeState::Invalid)
    }
}

pub struct Bundle2Encode<W> {
    state: EncodeState<W>,
    // Shared with WakeWriter. try_finish polls that writer with a noop waker.
    task_waker: Arc<Mutex<Waker>>,
}

struct StartState<W> {
    writer: W,
    compressor_type: CompressorType,
    header_buf: Cursor<Bytes>,
    parts: Vec<PartEncode>,
    task_waker: Arc<Mutex<Waker>>,
}

/// Substitutes the task waker for the noop waker `Compressor::try_finish` uses.
struct WakeWriter<W> {
    inner: W,
    task_waker: Arc<Mutex<Waker>>,
}

impl<W> WakeWriter<W> {
    fn into_inner(self) -> W {
        self.inner
    }
}

impl<W> WakeWriter<W>
where
    W: AsyncWrite + Unpin,
{
    fn poll_inner<T>(
        self: Pin<&mut Self>,
        poll: impl FnOnce(Pin<&mut W>, &mut Context<'_>) -> Poll<T>,
    ) -> Poll<T> {
        let this = self.get_mut();
        let waker = this.task_waker.lock().expect("waker lock").clone();
        let mut cx = Context::from_waker(&waker);
        poll(Pin::new(&mut this.inner), &mut cx)
    }
}

impl<W> AsyncWrite for WakeWriter<W>
where
    W: AsyncWrite + Unpin,
{
    fn poll_write(
        self: Pin<&mut Self>,
        _cx: &mut Context<'_>,
        buf: &[u8],
    ) -> Poll<io::Result<usize>> {
        self.poll_inner(|inner, cx| inner.poll_write(cx, buf))
    }

    fn poll_flush(self: Pin<&mut Self>, _cx: &mut Context<'_>) -> Poll<io::Result<()>> {
        self.poll_inner(|inner, cx| inner.poll_flush(cx))
    }

    fn poll_shutdown(self: Pin<&mut Self>, _cx: &mut Context<'_>) -> Poll<io::Result<()>> {
        self.poll_inner(|inner, cx| inner.poll_shutdown(cx))
    }
}

struct PartsState<W> {
    sink: PartSink<W>,
    current: Option<PartEncode>,
    rest: std::vec::IntoIter<PartEncode>,
    buffered: Option<Chunk>,
    phase: PartsPhase,
}

enum PartsPhase {
    Part,
    Flush,
    Eos,
    EosFlush,
}

impl<W> Future for Bundle2Encode<W>
where
    W: AsyncWrite + Unpin,
{
    type Output = Result<W>;

    fn poll(self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<Self::Output> {
        let this = self.get_mut();
        *this.task_waker.lock().expect("waker lock") = cx.waker().clone();
        let state = this.state.take();
        let (ret, state) = Self::poll_next(state, cx);
        this.state = state;
        ret
    }
}

impl<W> Bundle2Encode<W>
where
    W: AsyncWrite + Unpin,
{
    fn poll_next(state: EncodeState<W>, cx: &mut Context<'_>) -> (Poll<Result<W>>, EncodeState<W>) {
        match state {
            EncodeState::Start(start_state) => Self::poll_start(start_state, cx),
            EncodeState::Parts(parts) => Self::poll_parts(parts, cx),
            EncodeState::Finish(compressor) => Self::poll_finish(compressor),
            EncodeState::Done => panic!("polled Bundle2Encode future after it is complete"),
            EncodeState::Invalid => {
                panic!("polled Bundle2Encode future after it returned an error")
            }
        }
    }

    fn poll_start(
        mut start_state: StartState<W>,
        cx: &mut Context<'_>,
    ) -> (Poll<Result<W>>, EncodeState<W>) {
        match poll_write_all(&mut start_state.writer, &mut start_state.header_buf, cx) {
            Poll::Pending => (Poll::Pending, EncodeState::Start(start_state)),
            Poll::Ready(Err(err)) => (Poll::Ready(Err(err)), EncodeState::Invalid),
            Poll::Ready(Ok(())) => {
                let StartState {
                    writer,
                    compressor_type,
                    parts,
                    task_waker,
                    ..
                } = start_state;
                let parts = PartsState {
                    sink: FramedWrite::new(
                        Compressor::new(
                            WakeWriter {
                                inner: writer,
                                task_waker,
                            },
                            compressor_type,
                        ),
                        ChunkEncoder,
                    ),
                    current: None,
                    rest: parts.into_iter(),
                    buffered: None,
                    phase: PartsPhase::Part,
                };
                Self::poll_parts(parts, cx)
            }
        }
    }

    fn poll_parts(
        mut parts: PartsState<W>,
        cx: &mut Context<'_>,
    ) -> (Poll<Result<W>>, EncodeState<W>) {
        loop {
            match parts.phase {
                PartsPhase::Flush | PartsPhase::EosFlush => {
                    match Pin::new(&mut parts.sink).poll_flush(cx) {
                        Poll::Pending => return (Poll::Pending, EncodeState::Parts(parts)),
                        Poll::Ready(Err(err)) => {
                            return (Poll::Ready(Err(err)), EncodeState::Invalid);
                        }
                        Poll::Ready(Ok(())) => match parts.phase {
                            PartsPhase::Flush => parts.phase = PartsPhase::Part,
                            PartsPhase::EosFlush => {
                                return Self::poll_finish(parts.sink.into_inner());
                            }
                            PartsPhase::Part | PartsPhase::Eos => unreachable!(),
                        },
                    }
                }
                PartsPhase::Eos => match send_chunk(&mut parts, cx) {
                    Queued::Pending => return (Poll::Pending, EncodeState::Parts(parts)),
                    Queued::Err(err) => return (Poll::Ready(Err(err)), EncodeState::Invalid),
                    Queued::NeedChunk => {
                        parts.buffered = Some(Chunk::empty());
                    }
                    Queued::Sent => parts.phase = PartsPhase::EosFlush,
                },
                PartsPhase::Part => match send_chunk(&mut parts, cx) {
                    Queued::Pending => return (Poll::Pending, EncodeState::Parts(parts)),
                    Queued::Err(err) => return (Poll::Ready(Err(err)), EncodeState::Invalid),
                    Queued::Sent => {}
                    Queued::NeedChunk => {
                        if parts.current.is_none() {
                            match parts.rest.next() {
                                Some(part) => parts.current = Some(part),
                                None => {
                                    parts.phase = PartsPhase::Eos;
                                    continue;
                                }
                            }
                        }
                        match Pin::new(parts.current.as_mut().unwrap()).poll_next(cx) {
                            Poll::Pending => return (Poll::Pending, EncodeState::Parts(parts)),
                            Poll::Ready(Some(Ok(chunk))) => parts.buffered = Some(chunk),
                            Poll::Ready(Some(Err(err))) => {
                                return (Poll::Ready(Err(err)), EncodeState::Invalid);
                            }
                            Poll::Ready(None) => {
                                parts.current = None;
                                parts.phase = PartsPhase::Flush;
                            }
                        }
                    }
                },
            }
        }
    }

    fn poll_finish(compressor: Compressor<WakeWriter<W>>) -> (Poll<Result<W>>, EncodeState<W>) {
        match compressor.try_finish() {
            Ok(writer) => (Poll::Ready(Ok(writer.into_inner())), EncodeState::Done),
            Err((compressor, err)) => {
                if err.kind() == io::ErrorKind::WouldBlock {
                    (Poll::Pending, EncodeState::Finish(compressor))
                } else {
                    (
                        Poll::Ready(Err(Error::with_chain(
                            err,
                            ErrorKind::Bundle2Encode("error while completing write".into()),
                        ))),
                        EncodeState::Invalid,
                    )
                }
            }
        }
    }
}

enum Queued {
    Pending,
    Sent,
    NeedChunk,
    Err(Error),
}

fn send_chunk<W>(parts: &mut PartsState<W>, cx: &mut Context<'_>) -> Queued
where
    W: AsyncWrite + Unpin,
{
    let Some(chunk) = parts.buffered.take() else {
        return Queued::NeedChunk;
    };
    match Pin::new(&mut parts.sink).poll_ready(cx) {
        Poll::Pending => {
            parts.buffered = Some(chunk);
            Queued::Pending
        }
        Poll::Ready(Err(err)) => Queued::Err(err),
        Poll::Ready(Ok(())) => match Pin::new(&mut parts.sink).start_send(chunk) {
            Ok(()) => Queued::Sent,
            Err(err) => Queued::Err(err),
        },
    }
}

fn poll_write_all<W>(
    writer: &mut W,
    buf: &mut Cursor<Bytes>,
    cx: &mut Context<'_>,
) -> Poll<Result<()>>
where
    W: AsyncWrite + Unpin,
{
    while buf.has_remaining() {
        let chunk = buf.chunk();
        match Pin::new(&mut *writer).poll_write(cx, chunk) {
            Poll::Pending => return Poll::Pending,
            Poll::Ready(Ok(0)) => {
                return Poll::Ready(Err(io::Error::new(
                    io::ErrorKind::WriteZero,
                    "failed to write bundle header",
                )
                .into()));
            }
            Poll::Ready(Ok(n)) => buf.advance(n),
            Poll::Ready(Err(err)) => return Poll::Ready(Err(err.into())),
        }
    }
    Poll::Ready(Ok(()))
}

/// Ensure that Bundle2Encode is Send.
#[allow(dead_code)]
fn _assert_send() {
    fn _assert<T: Send>(_val: &T) {}

    let builder = Bundle2EncodeBuilder::new(Cursor::new(Vec::new()));
    _assert(&builder);
    _assert(&builder.build());
}
